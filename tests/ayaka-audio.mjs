import assert from "node:assert/strict";
import {readFileSync,existsSync} from "node:fs";
const read=p=>readFileSync(new URL(p,import.meta.url),"utf8");
const skills=new Function("game","get","_status",read("../character/skills/ayaka.js").replace(/^import .*;\r?\n/gm,"").replace("export default","return"))({}, {}, {});
const voices=new Function(read("../character/voices.js").replace("export default","return"))();
const lib={skill:skills,translate:voices,characterSubstitute:{}};
const get={info:id=>skills[id],character:()=>({tempname:[]})};
const Audio=new Function("get","lib",read("../../../noname/get/audio.js").replace(/^import .*;\r?\n/gm,"").replace(/export\s*\{[\s\S]*?\};?\s*$/,"")+"\nreturn Audio;")(get,lib);
const {skillVoiceGroups}=new Function(read("../ui/skill-voices.js").replace("export const","const").replace("export function","function")+"\nreturn {skillVoiceGroups};")();
assert.deepEqual(skillVoiceGroups.fan_bailu,["fan_bailu"]);
const bailu=Audio.skill({skill:"fan_bailu"}).audioList;
assert.deepEqual(new Set(bailu.map(x=>x.text)),new Set(["失礼了。","呵呵，请多关照。"]));
const take=Audio.skill({skill:"fan_binghua_take"}).audioList;
assert.deepEqual(new Set(take.map(x=>x.text)),new Set(["…拿下了！","樱吹雪。","神里流…霜灭！"]));
const role=read("../character/character.js").split(/\r?\n/).find(x=>x.includes("fan_ayaka:"));
const info=[...role.matchAll(/"die:([^"]+)"/g)].map(x=>x[1]);
const die=Audio.die({player:{name:"fan_ayaka"},info}).audioList;
assert.deepEqual(new Set(die.map(x=>x.text)),new Set(["失态了…","我还有…未尽之事…","让家族…蒙羞了…"]));
for(const clip of [...bailu,...die,...take])assert.ok(existsSync(new URL("../"+clip.file.replace(/^ext:原神\//,""),import.meta.url)));
console.log("Ayaka audio: native Bailu pool(2), death pool(3), final grouping, subtitles and files passed.");
