import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const status={},lib={},get={distance:(a,b)=>(b.seat-a.seat+8)%8},game={};
const engine=readFileSync(new URL('../../../noname/library/index.js',import.meta.url),'utf8');
const comparator=engine.match(/seat: (function\(a, b\) \{[\s\S]*?\n    \}),\r?\n    position:/)[1];
lib.sort={seat:new Function('lib','_status','game','get',`return (${comparator})`)(lib,status,game,get)};
const polyfill=readFileSync(new URL('../../../noname/init/polyfill.js',import.meta.url),'utf8');
const start=polyfill.indexOf('Object.defineProperty(Array.prototype, "sortBySeat",');
const end=polyfill.indexOf('Object.defineProperty(Array.prototype,',start+1);
new Function('lib',polyfill.slice(start,end))(lib);
const source=readFileSync(new URL('../character/skills/furina.js',import.meta.url),'utf8');
const skills=new Function('game','get','_status','setHuanyanEffect',source.replace(/^import .*;\r?\n/gm,'').replace('export default','return'))(game,get,status,()=>{});
let draws=[];
const players=Array.from({length:8},(_,i)=>({seat:i+1,alive:true,storage:{},isIn(){return this.alive},async draw(n){draws.push([this.seat,n]);}}));
const owner=players[3];game.me=owner;
owner.storage.fan_huanyan_targets=[players[0],players[2],players[7],players[5]];
status.currentPhase=owner;
await skills.fan_shanyao.content({}, {name:'recover'},owner);
assert.deepEqual(draws,[[4,2],[6,2],[8,2],[1,2],[3,2]]);
assert.deepEqual(owner.storage.fan_huanyan_targets.map(p=>p.seat),[1,3,8,6]);
draws=[];status.currentPhase=players[6];owner.storage.fan_zhongyu_state='success';
await skills.fan_shanyao.content({}, {name:'recover'},owner);
assert.deepEqual(draws,[[4,3],[8,3],[1,3],[3,3],[6,3]]);
draws=[];delete status.currentPhase;players[7].alive=false;
await skills.fan_shanyao.content({}, {name:'damage'},owner);
assert.deepEqual(draws,[[4,2],[6,2],[1,2],[3,2]]);
console.log('欢宴顺序检查通过：本地引擎排序、乱序选择、跨座次起点、回合外回退、离场排除及成功后摸牌数');
