"""Build small-frame assets without changing any original crop or detail image."""
from pathlib import Path
import re, json
from PIL import Image, ImageFilter

root = Path(__file__).resolve().parents[1]
characters = (root / 'character/character.js').read_text(encoding='utf-8')
ui = (root / 'ui/detail-portraits.js').read_text(encoding='utf-8')
paths = set(re.findall(r'ext:原神/(image/character/[^"\s]+)', characters))
paths.update('image/character/portraits/' + p for p in re.findall(r'([\w-]+-select[\w-]*\.png)', ui))
for prefix in ('hutao', 'hutao-skin1', 'hutao-skin2'):
    paths.update(f'image/character/portraits/{prefix}{suffix}.png' for suffix in ('', '-select'))
mapping = {}
out = root / 'image/character/smooth'
out.mkdir(exist_ok=True)
for path in sorted(paths):
    if '-avatar-20261027' in path and ('shenhe' in path or 'skirk' in path):
        continue  # Already approved, filtered small assets.
    source = root / path
    if not source.exists():
        raise FileNotFoundError(source)
    with Image.open(source) as im:
        transparent = 'A' in im.getbands() or 'transparency' in im.info
        # RGBa stores premultiplied colors: invisible RGB must not bleed into edges.
        im = im.convert('RGBA').convert('RGBa') if transparent else im.convert('RGB')
        width = min(300, im.width)
        size = (width, round(im.height * width / im.width))
        # Mild prefilter only when reducing; no sharpening or repeated filtering.
        radius = 0.4 * im.width / width if im.width > width else 0
        channels = []
        for channel in im.split():
            if radius:
                channel = channel.filter(ImageFilter.GaussianBlur(radius))
            channels.append(channel.resize(size, Image.Resampling.LANCZOS))
        im = Image.merge(im.mode, channels)
        if transparent:
            im = im.convert('RGBA')
        dest = f'image/character/smooth/{source.stem}.png'
        im.save(root / dest, optimize=True)
        mapping[path] = dest
(root / 'ui/smooth-portrait-map.js').write_text(
    '// Generated by tools/prepare_smooth_portraits.py. Original images remain intact.\n'
    + 'export default ' + json.dumps(mapping, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
print(f'Generated {len(mapping)} small-frame assets')
